// TestGoFpdfGenerator_GenerateTournamentReport_LargeGroupUsesLandscape covers
// a "La Liga"-style round-robin group with enough teams that the schedule +
// cross-table matrix + points columns no longer fit an A4 portrait page's
// printable width, forcing that table onto a landscape page. A small group
// follows it to confirm the report switches back to portrait afterward
// instead of leaving every later section landscape.
func TestGoFpdfGenerator_GenerateTournamentReport_LargeGroupUsesLandscape(t *testing.T) {
	gen := pdf.NewGoFpdfGenerator()

	var bigGroup []*player.Player
	for i := 0; i < 8; i++ {
		bigGroup = append(bigGroup, &player.Player{
			ID: fmt.Sprintf("big%d", i), FirstName: fmt.Sprintf("Player%d", i), LastName: "Liga", Gender: "M", SinglesElo: 1400,
		})
	}
	p1 := &player.Player{ID: "small1", FirstName: "Small", LastName: "One", Gender: "M", SinglesElo: 1400}
	p2 := &player.Player{ID: "small2", FirstName: "Small", LastName: "Two", Gender: "M", SinglesElo: 1400}

	participants := append([]*player.Player{}, bigGroup...)
	participants = append(participants, p1, p2)

	ev := &event.Event{
		ID: "e1", Name: "La Liga 2026", Type: "singles", Format: "round_robin", Status: "in_progress",
		StartDate: time.Now(), Participants: participants,
		Groups: []event.Group{
			{ID: "g1", Name: "Liga - Grupo Unico", Players: bigGroup},
			{ID: "g2", Name: "Liga - Grupo Chico", Players: []*player.Player{p1, p2}},
		},
	}

	pdfBytes, err := gen.GenerateTournamentReport(ev, nil)
	if err != nil {
		t.Fatalf("unexpected error generating tournament report: %v", err)
	}
	if !bytes.HasPrefix(pdfBytes, []byte("%PDF")) {
		t.Error("expected generated bytes to start with %PDF header")
	}
	// A landscape A4 page's MediaBox is width-major (841.89 x 595.28 pt),
	// the reverse of the portrait default (595.28 x 841.89 pt).
	if !bytes.Contains(pdfBytes, []byte("/MediaBox [0 0 841.89 595.28]")) {
		t.Error("expected the large group's table to render on a landscape page")
	}
}

