// mockPhotoDownloader returns a tiny valid JPEG for any path containing
// "front"/"back", an error for a path containing "broken", and otherwise
// fails the test if called unexpectedly.
type mockPhotoDownloader struct {
	t        *testing.T
	fetched  []string
	jpegData []byte
}

func newMockPhotoDownloader(t *testing.T) *mockPhotoDownloader {
	var buf bytes.Buffer
	img := image.NewRGBA(image.Rect(0, 0, 2, 2))
	if err := jpeg.Encode(&buf, img, nil); err != nil {
		t.Fatalf("failed to encode fixture JPEG: %v", err)
	}
	return &mockPhotoDownloader{t: t, jpegData: buf.Bytes()}
}

func (m *mockPhotoDownloader) Download(ctx context.Context, path string) ([]byte, error) {
	m.fetched = append(m.fetched, path)
	if strings.Contains(path, "broken") {
		return nil, fmt.Errorf("simulated download failure")
	}
	return m.jpegData, nil
}

func TestGoFpdfGenerator_GenerateEventReport_AppendsIDPhotos(t *testing.T) {
	downloader := newMockPhotoDownloader(t)
	gen := pdf.NewGoFpdfGenerator().WithPhotoDownloader(downloader)

	p1 := &player.Player{ID: "p1", FirstName: "Player", LastName: "One", Gender: "M", SinglesElo: 1500,
		NationalID: "001-123456-0001A", IDFrontPath: "id_front/p1.jpg", IDBackPath: "id_back/p1.jpg"}
	// p2 has no ID photos on file -- should be skipped entirely.
	p2 := &player.Player{ID: "p2", FirstName: "Player", LastName: "Two", Gender: "M", SinglesElo: 1400}
	// p3 has an unsupported extension (webp) that fpdf can't decode.
	p3 := &player.Player{ID: "p3", FirstName: "Player", LastName: "Three", Gender: "M", SinglesElo: 1400, IDFrontPath: "id_front/p3.webp"}
	// p4's download fails.
	p4 := &player.Player{ID: "p4", FirstName: "Player", LastName: "Four", Gender: "M", SinglesElo: 1400, IDFrontPath: "id_front/broken.jpg"}

	ev1 := &event.Event{
		ID: "e1", Name: "Sub Event 1", Type: "singles", Format: "round_robin", Status: "finished",
		Participants: []*player.Player{p1, p2, p3, p4},
	}

	tourn := &tournament.Tournament{ID: "t1", Name: "Grand Tournament", Events: []*event.Event{ev1}}

	pdfBytes, err := gen.GenerateEventReport(tourn, nil, true)
	if err != nil {
		t.Fatalf("unexpected error generating event report: %v", err)
	}
	if !bytes.HasPrefix(pdfBytes, []byte("%PDF")) {
		t.Error("expected generated bytes to start with %PDF header")
	}
	if len(downloader.fetched) != 3 {
		t.Errorf("expected 3 download attempts (p1 front+back, p4 front; p2 has none, p3's webp is skipped before download), got %d: %v", len(downloader.fetched), downloader.fetched)
	}
}

