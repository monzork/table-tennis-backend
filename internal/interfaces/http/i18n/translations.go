// T returns the translated string for the given locale and key.
// Falls back to English, then the key itself.
func T(locale, key string) string {
	if locale == "" {
		locale = "en"
	}
	if msgs, ok := Translations[locale]; ok {
		if val, ok := msgs[key]; ok {
			return val
		}
	}
	// Fallback to English
	if msgs, ok := Translations["en"]; ok {
		if val, ok := msgs[key]; ok {
			return val
		}
	}
	return key
}

// PrecomputedMaps holds pre-built translation maps for each supported language to optimize runtime lookups.
var PrecomputedMaps map[string]map[string]string

func init() {
	PrecomputedMaps = make(map[string]map[string]string)
	locales := []string{"en", "es"}
	for _, lang := range locales {
		m := make(map[string]string)
		for k := range Translations["en"] {
			m[k] = T(lang, k)
		}
		for k := range Translations[lang] {
			m[k] = T(lang, k)
		}
		PrecomputedMaps[lang] = m
	}
}
